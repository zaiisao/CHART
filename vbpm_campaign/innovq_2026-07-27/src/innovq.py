    ap.add_argument("--temp", type=float, default=0.3)
    ap.add_argument("--obs_w", type=float, default=1.0)
    ap.add_argument("--recon", default="bce", choices=["bce", "stmask", "stpool", "cramer", "hybrid"])
    ap.add_argument("--crop", type=int, default=1500)
    ap.add_argument("--fast", action="store_true")
    ap.add_argument("--no_abort", action="store_true")
    ap.add_argument("--tg", action="store_true")
    ap.add_argument("--gamma_phase", type=float, default=None)  # wrapped-Cauchy innovation prior scale
    ap.add_argument("--dec_freeze", action="store_true")  # keep the pretrained read-out fixed
    ap.add_argument("--tg_freeze", action="store_true")  # hold the level head after tg_pre
    ap.add_argument("--tg_pre", type=int, default=0)  # supervised init of the tempogram level head
    ap.add_argument("--dec_pre", type=int, default=0)   # fit decoders on ORACLE phase first
    ap.add_argument("--cram_anneal", type=int, default=0)  # steps to anneal CRAMER_LAM -> 0   # tempogram-fed init head (level from ACF, not mean-pool)  # criterion is calibrated to the warm-start regime   # parallel-in-time rollout (451x)   # 30s: TRUTH beats COAST by 46 nats here
    ap.add_argument("--smoke", action="store_true")
    A = ap.parse_args()
    TAG = A.tag or (("smoke_" if A.smoke else "") + f"{A.placement}_s{A.seed}")
    dev = "cuda:0"
    if A.gamma_phase is not None:
        # 5.5e-4 rad/frame prices phase correction out of existence: mu=5e-4 costs 282
        # nats/crop while the ENTIRE recon benefit of correct phase is ~117 nats.
        # Physical microtiming ~15ms @ 24 frames/beat is ~0.049 rad.
        # GP1 and R0 are DERIVED from RHO_P at import; rebinding RHO_P alone left
        # kl_phase_innov mixing a new RHO_P with a stale GP1 (93x understated KL) and
        # left R0 initialising rho_q at the OLD prior. Rebind all three together.
        global RHO_P, GP1, R0
        P.PHYS["gamma_phase"] = A.gamma_phase
        RHO_P = math.exp(-A.gamma_phase)
        GP1 = 1.0 - RHO_P
        R0 = softplus_inv(GP1)
        print(f"[prior] gamma_phase={A.gamma_phase:.4g} -> RHO_P={RHO_P:.6f} "
              f"GP1={GP1:.6e} R0={R0:.4f}", flush=True)
    if A.fast:
        global ROLLOUT_FN
        from rollout_vec_s import rollout_vec_s as _rvs
        ROLLOUT_FN = _rvs
        print("[fast] parallel-in-time rollout enabled (picard=8)", flush=True)
    torch.manual_seed(A.seed)
    rng = np.random.default_rng(A.seed)

    train = P.build_crops(P.load_songs("train"), n_per_song=2, seed=0, crop=A.crop, dev=dev)
    ev = P.build_crops(P.load_songs("eval"), n_per_song=1, seed=1, crop=A.crop, dev=dev)
    Ntr, T = train["b"].shape

    TEA = None
    if A.placement == "label":
        TEA = dict(phi=train["phi"], lt=train["lt"])
    elif A.placement != "cold":
        PF = pf_targets("train", 2, 0, A.crop, lt_src="phase", dev=dev)
        if A.placement == "pf_raw":
            TEA = dict(phi=PF["phi"], lt=PF["lt"])
        else:
            w = int(A.placement.replace("pf_sm", ""))
            sphi, slt = smooth_track(PF["phi"], w)
            TEA = dict(phi=sphi, lt=slt)
    if TEA is not None:
        dtc = torch.exp(1j * (TEA["phi"] - train["phi"]))
        tea_corr = float(torch.abs(dtc.mean()))                    # pooled (m2 logs)
        tea_corr_pc = float(torch.abs(dtc.mean(dim=1)).mean())     # per-crop (SPEC bracket)
    else:
        tea_corr = tea_corr_pc = float("nan")

    _CLS = InnovQ
    if A.tg:
        from innovq_tg import InnovQT as _CLS
        print("[tg] tempogram-fed init head enabled", flush=True)
    model = _CLS(s_phi=A.s_phi, s_lt=A.s_lt, rho1_max=A.rho1_max,
                 head_init_std=A.head_init_std).to(dev)
    d0, h0 = P.new_decoders(dev)
    dec, hdec = Cut(d0), Cut(h0)
    ALLP = lambda: list(model.parameters()) + list(d0.parameters()) + list(h0.parameters())
    if A.tg_pre > 0:
        # corr is ~entirely a function of TEMPO error (isolation: true-tempo 0.998 vs
        # model-tempo 0.270). The ELBO's tempo signal is ~1% of the loss level, below the
        # sampling noise floor, so the level head cannot learn it by descent. Initialize it
        # the way the read-out is initialized -- then ELBO-train. Objective is unchanged.
        _lvl = torch.log(2 * math.pi / (4.0 * torch.stack([
            torch.median(torch.diff(torch.nonzero(train["b"][i] > 0.5).squeeze(-1)).float())
            if (train["b"][i] > 0.5).sum() >= 8 else torch.tensor(float("nan"), device=dev)
            for i in range(Ntr)])))
        _ok = torch.nonzero(~torch.isnan(_lvl)).squeeze(-1)
        _op = torch.optim.AdamW([q for q in model.parameters() if q.requires_grad], lr=1e-3)
        for _s in range(A.tg_pre):
            _op.zero_grad()
            _sel = _ok[torch.randperm(len(_ok), device=dev)[:24]]
            _c = model.encode_posterior(train["h"][_sel], train["b"][_sel])
            _mu = model.init_head(torch.cat([_c.mean(1), _c[:, 0]], -1))[:, model.K + 3] + model.level_offset
            (_mu - _lvl[_sel]).abs().mean().backward(); _op.step()
        with torch.no_grad():
            _c = model.encode_posterior(train["h"][_ok[:200]], train["b"][_ok[:200]])
            _mu = model.init_head(torch.cat([_c.mean(1), _c[:, 0]], -1))[:, model.K + 3] + model.level_offset
            _m = float((_mu - _lvl[_ok[:200]]).abs().mean())
        print(f"[tg_pre] level head initialized, train MAE {100*_m:.2f}% (2% needed for corr>=0.82)", flush=True)
        if A.tg_freeze:
            # MEASURED: the ELBO drives log-tempo AWAY from truth (10.8% -> 37% in 75 steps,
            # worse than predicting the corpus mean). Hold the level head so corr can be
            # attributed to phase tracking rather than tempo drift.
            for _q in list(model.init_head.parameters()) + list(model.tg_embed.parameters()
                          if hasattr(model, "tg_embed") else []):
                _q.requires_grad_(False)
            print("[tg_freeze] level/init head FROZEN", flush=True)

    if A.dec_pre > 0:
        # At init the recon is phase-BLIND (+0.00% to a full phase scramble), so the
        # decoder's cheapest descent is the marginal beat density -- after which the
        # latent can never earn gradient back. Fit the read-out on the oracle trajectory
        # first so phase carries signal from ELBO step 1.
        _mi = train["m"].long().clamp(0, model.K - 1)
        mo = F.one_hot(_mi, model.K).float()
        if mo.dim() == 2:
            mo = mo.unsqueeze(1).expand(-1, T, -1)
        Zor = torch.cat([torch.cos(train["phi"]).unsqueeze(-1), torch.sin(train["phi"]).unsqueeze(-1),
                         train["lt"].unsqueeze(-1), mo], -1)
        od = torch.optim.Adam(list(d0.parameters()) + list(h0.parameters()), lr=3e-3)
        for _s in range(A.dec_pre):
            od.zero_grad()
            sel = torch.randperm(Ntr, device=dev)[:16]
            rb_, rd_, ro_ = P.recon_terms(dec, hdec, Zor[sel], train["b"][sel], train["db"][sel],
                                          train["obs"][sel], recon=A.recon)
            (rb_ + rd_ + ro_).mean().backward(); od.step()
        print(f"[dec_pre] fit read-out on oracle phase for {A.dec_pre} steps", flush=True)
        # sensitivity check: recon must RISE when phase is scrambled, else the pretrain failed
        with torch.no_grad():
            _p2 = (train["phi"][:16] + 0.05 * torch.arange(T, device=dev).float()) % TWO_PI
            _Z2 = torch.cat([torch.cos(_p2).unsqueeze(-1), torch.sin(_p2).unsqueeze(-1),
                             train["lt"][:16].unsqueeze(-1), mo[:16]], -1)
            _a = P.recon_terms(dec, hdec, Zor[:16], train["b"][:16], train["db"][:16],
                               train["obs"][:16], recon=A.recon)
            _b = P.recon_terms(dec, hdec, _Z2, train["b"][:16], train["db"][:16],
                               train["obs"][:16], recon=A.recon)
            _r0 = float((_a[0] + _a[1]).mean()); _r1 = float((_b[0] + _b[1]).mean())
        print(f"[dec_pre] phase sensitivity: {_r0:.1f} -> {_r1:.1f} ({100*(_r1-_r0)/abs(_r0):+.2f}%)", flush=True)
        if A.dec_freeze:
            for _p in list(d0.parameters()) + list(h0.parameters()):
                _p.requires_grad_(False)
            ALLP = lambda: [q for q in model.parameters() if q.requires_grad]
            print("[dec_freeze] read-out FROZEN: latent is the only route to lower recon", flush=True)
    print(f"[{TAG}] train {Ntr}x{T} | eval {ev['b'].shape[0]}x1000 | "
          f"corr(teacher,truth) pooled={tea_corr:.4f} percrop={tea_corr_pc:.4f} | "
          f"rho_p={RHO_P:.6f} s_phi={model.s_phi} "
          f"s_lt={model.s_lt} rho1_max={model.rho1_max}", flush=True)

    # ---------------- SMOKE ----------------
    if A.smoke:
        smoke = dict(tag=TAG, seed=A.seed)
        h3, b3 = train["h"][:3], train["b"][:3]
        # (i) zero innovations -> EXACT prior-mean recursion
        with torch.no_grad():
            ro = rollout(model, h3, b3, sample=False, zero_innov=True)
            phi, lt = ro["phi"], ro["lt"]
            cur = phi[:, 0].clone()
            dmax = 0.0
            for t in range(1, T):
                cur = (cur + torch.exp(lt[:, t - 1].clamp(-12.0, 6.0))) % TWO_PI
                dmax = max(dmax, float(wrap(phi[:, t] - cur).abs().max()))
            smoke["i_max_abs_recursion_diff_rad"] = dmax
            smoke["i_lt_drift"] = float((lt[:, -1] - lt[:, 0]).abs().max())
        # (ii) kl_phase at zero-mean innovations vs independent float64 analytic
        with torch.no_grad():
            kl_code = float(ro["kl_p"].mean())
            mu = ro["MU"].double().cpu().numpy()
            rq = (1.0 - ro["SQ"].double()).cpu().numpy()
            num = 1.0 - 2.0 * rq * RHO_P * np.cos(mu) + (rq * RHO_P) ** 2
            den = (1.0 - rq ** 2) * (1.0 - RHO_P ** 2)
            per_step = np.log(num / den).sum(1)
            r1 = ro["rho1"].double().cpu().numpy()
            m1 = ro["mu_phi1"].double().cpu().numpy()
            rp1 = 1e-6
            t1 = np.log((1 - 2 * r1 * rp1 * np.cos(m1 - math.pi) + (r1 * rp1) ** 2)
                        / ((1 - r1 ** 2) * (1 - rp1 ** 2)))
            kl_ana = float((per_step + t1).mean())
            smoke["ii_kl_phase_code"] = kl_code
            smoke["ii_kl_phase_analytic64"] = kl_ana
            smoke["ii_ratio"] = kl_code / kl_ana if kl_ana != 0 else float("inf")
