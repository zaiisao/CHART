def softplus_inv(y):
    return math.log(math.expm1(y))


R0 = softplus_inv(GP1)                 # innov rho bias: zero head output -> rho_q = rho_p
B_SLT0 = softplus_inv(T_SCALE - 1e-5)  # innov s_lv bias: zero output -> s_lv = sigma_dlt
B_LS0 = softplus_inv(INIT_LV_S - 0.05)  # init level-scale bias: zero output -> 0.3


def wrap(x):
    return (x + math.pi) % TWO_PI - math.pi


def kl_phase_innov(mu_eps, sq):
    """Closed-form per-step innovation KL: KL(WC(mu_eps, 1-sq) || WC(0, rho_p)).

    Cancellation-free form (SPEC (b), 'numerically superior accountant'):
      num = d^2 + 4 rho_q rho_p sin^2(mu/2),  d = 1 - rho_q rho_p = sq + (1-sq)(1-rho_p)
      den = (1-rho_q^2)(1-rho_p^2) = sq (2-sq) (1-rho_p)(1+rho_p)
    computed in float64 with sq = 1-rho_q taken DIRECTLY from the softplus output
    (never as 1-rho after rounding). Exactly 0 at mu=0, sq=1-rho_p.
    """
    mu = mu_eps.double()
    s = sq.double().clamp(1e-9, 0.5)
    rq = 1.0 - s
    d = s + rq * GP1
    num = d * d + 4.0 * rq * RHO_P * torch.sin(mu / 2.0) ** 2
    den = s * (2.0 - s) * GP1 * (1.0 + RHO_P)
    return torch.log(num / den)


class InnovQ(VB.BarPointerVAE_B):
    """BarPointerVAE_B trunk + innovation-space posterior heads (SPEC (a))."""

    def __init__(self, s_phi=0.05, s_lt=0.0025, rho1_max=0.9, head_init_std=1e-3):
        super().__init__(h_dim=2, hidden=128, num_meters=4, obs_dim=2, obs_type="bern")
        self.s_phi = float(s_phi)          # mutable (anneal)
        self.s_lt = float(s_lt)
        self.rho1_max = float(rho1_max)
        hid = self.hidden
        # (i) t=1 head: [mean_t c_t, c_1] -> K meter logits | u,v | rho1_raw | lv_mu | lv_s_raw
        self.init_head = nn.Sequential(
            nn.Linear(2 * hid, hid), nn.Tanh(), nn.Linear(hid, self.K + 5))
        # (ii) innovation head: [c_t, z_feat(z_{t-1})] -> phi_raw | rho_raw | lt_raw | s_lv_raw
        self.innov_head = nn.Sequential(
            nn.Linear(hid + self.z_feat_dim, hid), nn.Tanh(), nn.Linear(hid, 4))
        with torch.no_grad():
            # small (not zero) final weights: near-neutral start, but gradient reaches
            # every layer from step 1 (smoke check iii).
            for lin in (self.init_head[-1], self.innov_head[-1]):
                lin.weight.normal_(0.0, head_init_std)
                lin.bias.zero_()
            self.init_head[-1].bias[self.K] = 1.0        # (u,v)=(1,0) -> mu_phi1 = 0
            self.init_head[-1].bias[self.K + 4] = B_LS0  # s_l1 init = 0.3 (prior init scale)
        Pi = torch.full((self.K, self.K), (1.0 - P.PHYS["meter_self"]) / (self.K - 1))
        Pi.fill_diagonal_(P.PHYS["meter_self"])
        self.register_buffer("Pi_phys", Pi)


def rollout(model, h, b, *, sample=True, temperature=0.3, zero_innov=False, u_eps=1e-4):
    """q's sampler = prior recursion + encoder nudges. Full BPTT (no detach).

    Returns Z [B,T,7], phi/lt trajectories, per-crop KLs (phase/level/meter; dev pinned
    -> 0 by construction), and detached diagnostics (MU, SQ, saturation).
    """
    Bn, T, _ = h.shape
    dev = h.device
    K = model.K
    dof_t = torch.tensor(DOF, device=dev)
    tsc = torch.full((Bn,), T_SCALE, device=dev)
    zero = torch.zeros(Bn, device=dev)

    ctx = model.encode_posterior(h, b)                                   # [B,T,hid]
    init = model.init_head(torch.cat([ctx.mean(1), ctx[:, 0]], -1))      # [B,K+5]
    m_logits = init[:, :K]
    mu_phi1 = torch.atan2(init[:, K + 1], init[:, K]) % TWO_PI
    rho1 = (torch.sigmoid(init[:, K + 2]) * model.rho1_max).clamp(1e-6, 1 - 1e-6)
    mu_l1 = init[:, K + 3] + model.level_offset
    s_l1 = F.softplus(init[:, K + 4]) + 0.05

    if sample:
        u1 = torch.rand(Bn, device=dev).clamp(u_eps, 1.0 - u_eps)
        phi = (mu_phi1 + (-torch.log(rho1)) * torch.tan(math.pi * (u1 - 0.5))) % TWO_PI
        level = torch.distributions.StudentT(dof_t, mu_l1, s_l1).rsample()
        dv = DEV_SIGMA * torch.randn(Bn, device=dev)
        meter = gumbel_softmax(m_logits, temperature)
    else:
        phi, level, dv = mu_phi1, mu_l1, zero
        meter = F.softmax(m_logits / max(temperature, 1e-6), -1)
    lt = level + dv

    # t=1 KLs vs the physical init (phase WC(pi,1e-6); level St-t; meter uniform; dev q==p)
    kl_p = kl_wrapped_cauchy(mu_phi1, rho1,
                             torch.full_like(mu_phi1, math.pi),
                             torch.full_like(mu_phi1, 1e-6)).double()
    kl_l = P.kl_t_mc(dof_t, mu_l1, s_l1, dof_t,
                     torch.full((Bn,), INIT_LV_MU, device=dev),
                     torch.full((Bn,), INIT_LV_S, device=dev), level)
    kl_m = kl_categorical(torch.log_softmax(m_logits, -1),
                          torch.full((Bn, K), -math.log(K), device=dev))
    n_cross = torch.ones(Bn, device=dev)

    z_feats = [model.z_features(meter, phi, lt)]
    phis, lts = [phi], [lt]
    MU, SQ = [], []
    for t in range(1, T):
        zf = model.z_features(meter, phi, lt)
        out = model.innov_head(torch.cat([ctx[:, t], zf], -1))
        mu_eps = torch.tanh(out[:, 0]) * model.s_phi
        sq = F.softplus(out[:, 1] + R0).clamp(1e-6, 0.5)      # = 1 - rho_q; ONE shared clamp feeds sampler AND KL (review M2)
        mu_lt = torch.tanh(out[:, 2]) * model.s_lt
        s_lv = F.softplus(out[:, 3] + B_SLT0) + 1e-5
        if zero_innov:
            mu_eps = mu_eps * 0.0
            mu_lt = mu_lt * 0.0

        tempo = torch.exp(lt.clamp(-12.0, 6.0))
        advance = phi + tempo
        cross = (advance >= TWO_PI).to(h.dtype)

        if sample:
            u = torch.rand(Bn, device=dev).clamp(u_eps, 1.0 - u_eps)
            gam_q = -torch.log1p(-sq)         # = -log(1-sq) = -log rho_q  (blind-T2 fix: was -log(sq) ~ 7.5 -> uniform phase)
            eps = mu_eps + gam_q * torch.tan(math.pi * (u - 0.5))
            eps_lt = torch.distributions.StudentT(dof_t, mu_lt, s_lv).rsample()
            dv = DEV_SIGMA * torch.randn(Bn, device=dev)
            m_draw = gumbel_softmax(m_logits, temperature)
        else:
            eps, eps_lt, dv = mu_eps, mu_lt, zero
            m_draw = F.softmax(m_logits / max(temperature, 1e-6), -1)

        meter_prev = meter
        phi = (advance + eps) % TWO_PI
        level = level + eps_lt
        lt = level + dv
        meter = torch.where(cross.unsqueeze(-1) > 0.5, m_draw, meter_prev)

        kl_p = kl_p + kl_phase_innov(mu_eps, sq)              # sample-path independent
        kl_l = kl_l + P.kl_t_mc(dof_t, mu_lt, s_lv, dof_t, zero, tsc, eps_lt)
        kl_m = kl_m + cross * kl_categorical(
            torch.log_softmax(m_logits, -1),
            torch.log(meter_prev @ model.Pi_phys + 1e-9))
        n_cross = n_cross + cross

        z_feats.append(model.z_features(meter, phi, lt))
        phis.append(phi); lts.append(lt)
        MU.append(mu_eps.detach()); SQ.append(sq.detach())

    MU = torch.stack(MU, 1); SQ = torch.stack(SQ, 1)          # [B,T-1] detached
    return dict(Z=torch.stack(z_feats, 1),
                phi=torch.stack(phis, 1), lt=torch.stack(lts, 1),
                kl_p=kl_p.float(), kl_l=kl_l, kl_m=kl_m,
                kl_dv=torch.zeros(Bn, device=dev),            # dev pinned: q == p
                n_cross=n_cross, MU=MU, SQ=SQ,
                init_vec=init, ctx=ctx,
                mu_phi1=mu_phi1.detach(), rho1=rho1.detach(),
                mu_l1=mu_l1.detach(), s_l1=s_l1.detach(),
                mean_abs_innov=float(MU.abs().mean()))


def _diag_fill(ro, model):
    ro["sat_frac"] = float((ro["MU"].abs() > 0.8 * model.s_phi).float().mean())
    ro["rho_q_mean"] = float((1.0 - ro["SQ"]).mean())
    ro["max_sq"] = float(ro["SQ"].max())
    return ro


