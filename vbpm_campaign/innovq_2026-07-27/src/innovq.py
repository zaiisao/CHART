ROLLOUT_FN = None

def _rollout(model, h, b, **kw):
    if ROLLOUT_FN is None or kw.get("zero_innov"):
        return rollout(model, h, b, **kw)
    kw.pop("u_eps", None); kw.pop("zero_innov", None)
    return ROLLOUT_FN(model, h, b, n_picard=8, **kw)


def elbo_innovq(model, D, dec, hdec, *, idx=None, beta=1.0, sample=True,
                temperature=0.3, obs_w=1.0, recon="bce", zero_innov=False):
    h, b, db, obs = D["h"], D["b"], D["db"], D["obs"]
    if idx is not None:
        h, b, db, obs = h[idx], b[idx], db[idx], obs[idx]
    ro = _rollout(model, h, b, sample=sample, temperature=temperature, zero_innov=zero_innov)
    _diag_fill(ro, model)
    rb, rd, roo = P.recon_terms(dec, hdec, ro["Z"], b, db, obs, recon=recon)
    L_kl = ro["kl_p"] + ro["kl_l"] + ro["kl_m"] + ro["kl_dv"]
    loss = (rb + rd + obs_w * roo + beta * L_kl).mean()
    info = dict(loss=float(loss), recon_beat=float(rb.mean()), recon_db=float(rd.mean()),
                recon_obs=float(roo.mean()), kl=float(L_kl.mean()),
                kl_phase=float(ro["kl_p"].mean()), kl_level=float(ro["kl_l"].mean()),
                kl_meter=float(ro["kl_m"].mean()), kl_dev=0.0,
                n_cross=float(ro["n_cross"].mean()),
                mean_abs_innov=float(ro["MU"].abs().mean()),
                sat_frac=ro["sat_frac"], rho_q=ro["rho_q_mean"], max_sq=ro["max_sq"],
                rho1=float(ro["rho1"].mean()), s_phi=model.s_phi)
    return loss, info, ro


@torch.no_grad()
def probe(model, D, dec, hdec, TEA=None, chunk=48, recon="bce", temperature=0.3):
    """Mean-rollout probe (sample=False): corr-to-truth, corr-to-teacher, TF-F, KL
    breakdown, innovation diagnostics. Mirrors m2_distill.probe conventions."""
    model.eval()
    Bn = D["h"].shape[0]
    phis, kls = [], dict(kl_phase=[], kl_level=[], kl_meter=[], rb=[], rd=[], ro=[])
    mu_abs, sat, rhoq = [], [], []
    msq = 0.0
    for i in range(0, Bn, chunk):
        idx = torch.arange(i, min(i + chunk, Bn), device=D["h"].device)
        _, info, ro = elbo_innovq(model, D, dec, hdec, idx=idx, beta=1.0, sample=False,
                                  temperature=temperature, recon=recon)
        phis.append(ro["phi"])
        kls["kl_phase"].append(ro["kl_p"]); kls["kl_level"].append(ro["kl_l"])
        kls["kl_meter"].append(ro["kl_m"])
        mu_abs.append(ro["MU"].abs().flatten()); sat.append(
            (ro["MU"].abs() > 0.8 * model.s_phi).float().flatten())
        rhoq.append((1.0 - ro["SQ"]).flatten())
        msq = max(msq, float(ro["SQ"].max()))
    phi = torch.cat(phis, 0)
    dl = torch.exp(1j * (phi - D["phi"]))
    corr = float(torch.abs(dl.mean()))                       # POOLED resultant (m2 convention)
    corr_pc = float(torch.abs(dl.mean(dim=1)).mean())        # PER-CROP resultant (SPEC bracket convention)
    if TEA is not None:
        dt = torch.exp(1j * (phi - TEA["phi"]))
        ct = float(torch.abs(dt.mean()))
        ct_pc = float(torch.abs(dt.mean(dim=1)).mean())
    else:
        ct = ct_pc = float("nan")
    Fs, Fc = [], []
    for i in range(Bn):
        ref = np.where(D["b"][i].cpu().numpy() > 0.5)[0] / FPS
        if len(ref) < 4:
            continue
        ph = phi[i].cpu().numpy(); mi = int(D["m"][i])
        Fs.append(f_measure(ref, beats_from_barphase(ph, mi, FPS)))       # m2 convention
        Fc.append(f_measure(ref, beats_from_barphase(ph, mi + 1, FPS)))   # corrected bpb
    model.train()
    return dict(tf_F=float(np.mean(Fs)), tf_F_corr=float(np.mean(Fc)), corr=corr,
                corr_percrop=corr_pc, corr_teacher=ct, corr_teacher_percrop=ct_pc,
                max_sq=msq,
                kl_phase=float(torch.cat(kls["kl_phase"]).mean()),
                kl_level=float(torch.cat(kls["kl_level"]).mean()),
                kl_meter=float(torch.cat(kls["kl_meter"]).mean()),
                mean_abs_innov=float(torch.cat(mu_abs).mean()),
                sat_frac=float(torch.cat(sat).mean()),
                rho_q=float(torch.cat(rhoq).mean()))


def placement_loss(model, D, TEA, idx, temperature=0.3, w_roll=1.0):
    """Placement v2 (blind-T3 fix). Three terms, phi/lt supervision only (m2 latents):
      (1) L_roll: m2's free-rollout trajectory loss (unchanged) -- BPTT credit assignment;
      (2) L_init: DIRECT anchor of the t=1 head to the teacher's absolute offset
          (supervise raw (u,v) toward (cos,sin) of tea_phi[:,0], level mu to tea_lt[:,0])
          -- blind T3 showed absolute offsets never align through L_roll alone
          (pooled corr 0.044) and innovations balloon 35x instead (kl_phase 1157);
      (3) L_tf: teacher-forced per-frame innovation matching -- the innov head is driven
          with the TEACHER state z_{t-1} and its mu_eps/mu_lt are regressed on the
          teacher's own innovations eps* = wrap(dphi - exp(lt_{t-1})), dlt*; normalized
          by the bounds so the loss is order-1.  All three end before handover."""
    h, b = D["h"][idx], D["b"][idx]
    tp, tl = TEA["phi"][idx], TEA["lt"][idx]
    if w_roll > 0.0:
        ro = _rollout(model, h, b, sample=False, temperature=temperature)
        L_roll = (1 - torch.cos(ro["phi"] - tp)).mean() * 10 \
            + ((ro["lt"] - tl) ** 2).mean()
        ctx = ro["ctx"]
    else:
        L_roll = torch.zeros((), device=h.device)
        ctx = model.encode_posterior(h, b)
    K = model.K
    # DENSE init supervision (v2.2): the single-point [mean,ctx0] regression is
    # unlearnable (400-step pilot: resultant plateau 0.10); the SAME head supervised at
    # every frame (m2-dense) reaches frame-0 resultant-vs-truth 0.486 by s300. The
    # rollout still consumes only the frame-0 application of this head.
    T = ctx.shape[1]
    inp = torch.cat([ctx.mean(1, keepdim=True).expand(-1, T, -1), ctx], -1)
    init_all = model.init_head(inp)                                  # [B,T,K+5]
    L_init = ((init_all[..., K] - torch.cos(tp)) ** 2
              + (init_all[..., K + 1] - torch.sin(tp)) ** 2).mean() \
        + ((init_all[..., K + 3] + model.level_offset - tl) ** 2).mean()
    init = init_all[:, 0]
    meter = F.softmax(init[:, :K] / max(temperature, 1e-6), -1)
    Tm1 = tp.shape[1] - 1
    zf = model.z_features(meter.unsqueeze(1).expand(-1, Tm1, -1), tp[:, :-1], tl[:, :-1])
    out = model.innov_head(torch.cat([ctx[:, 1:], zf], -1))
    b_phi, b_lt = 0.95 * model.s_phi, 0.95 * model.s_lt
    eps_star = wrap(tp[:, 1:] - tp[:, :-1]
                    - torch.exp(tl[:, :-1].clamp(-12.0, 6.0))).clamp(-b_phi, b_phi)
    dlt_star = (tl[:, 1:] - tl[:, :-1]).clamp(-b_lt, b_lt)
    mu_eps = torch.tanh(out[..., 0]) * model.s_phi
    mu_lt = torch.tanh(out[..., 2]) * model.s_lt
    L_tf = (((mu_eps - eps_star) / model.s_phi) ** 2).mean() \
        + (((mu_lt - dlt_star) / model.s_lt) ** 2).mean()
    return w_roll * L_roll + L_init + L_tf, dict(L_roll=float(L_roll),
                                                 L_init=float(L_init), L_tf=float(L_tf),
                                                 w_roll=float(w_roll))


def smooth_track(phi, win):
    """Placement-free smoothing of a phase track (copied verbatim from toy_kl_verify),
    v2.1: the lt track gets a SECOND boxcar (same win) so teacher tempo increments are
    representable by the bounded innovation head (dlt* out-of-bound 65% -> 17%); the
    teacher PHASE is untouched and remains exactly reproducible from (lt_smooth, eps*)
    [measured max reconstruction err 4.8e-6 rad; corr-to-truth unchanged 0.633533]."""
    d = wrap(phi[:, 1:] - phi[:, :-1])
    k = torch.ones(1, 1, win, device=phi.device) / win
    ds = F.conv1d(F.pad(d.unsqueeze(1), (win // 2, win // 2), mode="replicate"), k).squeeze(1)
    out = torch.cat([phi[:, :1], phi[:, :1] + torch.cumsum(ds, 1)], 1)
    lt = torch.log(ds.clamp(1e-4, 1.0))
    lt = torch.cat([lt[:, :1], lt], 1)[:, :phi.shape[1]]
    lt = F.conv1d(F.pad(lt.unsqueeze(1), (win // 2, win // 2), mode="replicate"), k).squeeze(1)
    return out % TWO_PI, lt


class Cut(nn.Module):
    """Cut log-tempo from the decoder input (m2 convention)."""
    def __init__(self, m):
        super().__init__()
        self.m = m

    def forward(self, z):
        return self.m(torch.cat([z[..., :2], torch.zeros_like(z[..., 2:3]), z[..., 3:]], -1))


